export const scoreBlockAnswers = (
  block: HrQuizBlock,
  answers: Record<string, string>
): { correct: number; total: number; percent: number } => {
  let correct = 0;
  for (const q of block.questions) {
    const picked = answers[q.id];
    const right = q.options.find((o) => o.correct)?.id;
    if (picked && picked === right) correct += 1;
  }
  const total = block.questions.length;
  const percent = total ? Math.round((correct / total) * 100) : 0;
  return { correct, total, percent };
};

/** 0–100% → шкала радара 1–10 */
export const percentToRadarScore = (percent: number): number =>
  Math.max(1, Math.min(10, Math.round(percent / 10) || 1));

/** 0–100% → уровень матрицы 0–4 */
export const percentToCompetencyLevel = (percent: number): 0 | 1 | 2 | 3 | 4 => {
  if (percent >= 90) return 4;
  if (percent >= 70) return 3;
  if (percent >= 50) return 2;
  if (percent >= 25) return 1;
  return 0;
};
