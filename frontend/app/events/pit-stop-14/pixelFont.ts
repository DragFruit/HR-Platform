/** Латиница, совпадающая по начертанию с кириллицей. */
const SAME: Record<string, string> = { A: 'А', B: 'В', C: 'С', E: 'Е', H: 'Н', K: 'К', M: 'М', O: 'О', P: 'Р', T: 'Т', X: 'Х' };

export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const GLYPH_GAP = 1;

const glyph = (ch: string): string[] | null => {
  const key = SAME[ch] ?? ch;
  const g = G[key];
  return g ? g.split('|') : null;
};

export const pixelTextWidth = (text: string, scale = 1) =>
  Math.max(0, text.length * (GLYPH_W + GLYPH_GAP) - GLYPH_GAP) * scale;

export function drawPixelText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  scale = 1
) {
  let cx = Math.round(x);
  for (const ch of text.toUpperCase()) {
    const rows = glyph(ch);
    if (rows) {
      rows.forEach((row, ry) => {
        for (let rx = 0; rx < GLYPH_W; rx++) {
          if (row[rx] === '#') ctx.fillRect(cx + rx * scale, Math.round(y) + ry * scale, scale, scale);
        }
      });
    }
    cx += (GLYPH_W + GLYPH_GAP) * scale;
  }
}
