/**
 * Палитра «Огонька 2027» — ровно 8 цветов из спеки (docs/quests/ogonek-2027.md,
 * раздел 2). Больше цветов в спрайтах не бывает: индекс в строке спрайта это
 * индекс в этом массиве, символ `.` — прозрачность.
 *
 * Менять состав нельзя: на эту палитру опираются и спрайты, и CSS-токены,
 * и редактор игрушки (в нём ровно эти 8 кнопок).
 */

export const OGONEK_PALETTE = [
  '#7d1f28', // 0 фон ковра, бордовый
  '#1f4136', // 1 второй фон и бордюр, тёмно-хвойный
  '#e8d7b4', // 2 светлое поле медальона, кремовый
  '#d99a2b', // 3 тёплый акцент, охра
  '#2f7f7a', // 4 холодный акцент, бирюза
  '#1a1412', // 5 тень и контур, почти чёрный
  '#e8a87c', // 6 тёплый светлый, персиковый
  '#f5efe3'  // 7 блик, белый
] as const;

export type OgonekColorIndex = 0 | 1 | 2 | 3 | 4 | 5 | 6 | 7;

export const OGONEK_COLOR_NAMES: Record<OgonekColorIndex, string> = {
  0: 'бордовый',
  1: 'хвойный',
  2: 'кремовый',
  3: 'охра',
  4: 'бирюза',
  5: 'контур',
  6: 'персиковый',
  7: 'блик'
};

/** Цвет по символу строки спрайта. `null` — прозрачный пиксель. */
export function ogonekColorAt(ch: string): string | null {
  if (ch === '.' || ch === ' ') return null;
  const i = Number(ch);
  if (!Number.isInteger(i) || i < 0 || i > 7) return null;
  return OGONEK_PALETTE[i] ?? null;
}
