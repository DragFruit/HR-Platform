export const OGONEK_DAYS: OgonekDay[] = DRAFTS.map((d) => ({
  ...d,
  dateIso: OGONEK_DAY_DATES[d.id]!,
  weekday: WEEKDAYS[d.id]!
}));

export function ogonekDayById(id: number): OgonekDay {
  const found = OGONEK_DAYS.find((d) => d.id === id);
  if (!found) throw new Error(`ogonek: нет окна ${id}`);
  return found;
}

/**
 * Звания по числу открытых окон (спека, раздел 4b, пункт 2).
 * Это не награда и не лидерборд: просто видно, кто как далеко прошёл.
 */
export const OGONEK_RANKS: OgonekRank[] = [
  { from: 0, title: 'Прохожий' },
  { from: 1, title: 'Снегирь' },
  { from: 3, title: 'Фонарщик' },
  { from: 6, title: 'Ёлочный мастер' },
  { from: 9, title: 'Снежных дел мастер' },
  { from: 12, title: 'Хранитель огонька' },
  { from: 15, title: 'Хозяин ковра' },
  { from: 19, title: 'Дед Мороз' }
];

export function ogonekRankFor(opened: number): string {
  let title = OGONEK_RANKS[0]!.title;
  for (const r of OGONEK_RANKS) if (opened >= r.from) title = r.title;
  return title;
}

